#!/usr/bin/env node
// Vendors the ECC pieces listed in vendor/ecc.manifest.json from a local ECC checkout,
// regenerates vendor/ecc.index.md and writes a review report (METODO.md §11).
// Usage: node scripts/ecc-sync.mjs <ecc-checkout> --release <tag> --commit <sha> [--report <file>]
// Exit 0 = synced and clean, 1 = synced with findings for the human reviewer, 2 = cannot sync.
import { readFileSync, writeFileSync, existsSync, rmSync, cpSync, readdirSync, statSync, mkdirSync } from 'node:fs';
import { join, dirname, relative } from 'node:path';
import { pathToFileURL, fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');

// Content that must never enter silently. Each hit is a finding for the reviewer, not an auto-reject.
export const RED_FLAGS = [
  [/npx\s+-y\s+(?!(?:@[\w.-]+\/)?[\w.-]+@\d)/, 'npx -y without a pinned version'],
  [/claude\s+(?:-p|--print)\b/, 'hidden claude -p call'],
  [/~\/\.claude\/settings(?:\.local)?\.json|includeCoAuthoredBy/, 'touches user Claude settings'],
  [/\b(?:ECC Pro|sponsor(?:ed|s)?\b|Itô|ito\.com)/i, 'promotional / sponsor content'],
  [/\b(?:curl|wget|Invoke-WebRequest)\b[^\n]*\|\s*(?:sh|bash|iex)/i, 'pipe-to-shell download'],
];

export const frontmatter = (text) => {
  const m = text.match(/^---\r?\n([\s\S]*?)\r?\n---/);
  if (!m) return null;
  const get = (k) => m[1].match(new RegExp(`^${k}:\\s*(.+)$`, 'm'))?.[1].trim().replace(/^["']|["']$/g, '');
  return { name: get('name'), description: get('description') };
};

const walk = (p) => statSync(p).isDirectory() ? readdirSync(p).flatMap((n) => walk(join(p, n))) : [p];
const mainFile = (dir, item) => item.kind === 'skill' ? join(dir, item.path, 'SKILL.md') : join(dir, item.path);
const readFm = (file) => existsSync(file) && statSync(file).isFile() ? frontmatter(readFileSync(file, 'utf8')) : null;
const URL_RE = /https?:\/\/[^\s)"'`<>\]]+/g;

export function scan(vendorDir, manifest, previousUrls = new Set()) {
  const findings = [];
  const urls = new Set();
  for (const item of manifest.include) {
    const base = join(vendorDir, item.path);
    if (!existsSync(base)) {
      findings.push(item.pending
        ? { path: item.path, issue: 'pending: not in this release yet' }
        : { path: item.path, issue: 'missing upstream (renamed or deleted)', blocking: true });
      continue;
    }
    if (item.pending) findings.push({ path: item.path, issue: 'now released: remove "pending" from the manifest' });
    if (['agent', 'skill', 'command'].includes(item.kind)) {
      const fm = readFm(mainFile(vendorDir, item));
      if (!fm?.description && item.kind !== 'command') findings.push({ path: item.path, issue: 'missing or invalid frontmatter', blocking: true });
    }
    for (const f of walk(base)) {
      const rel = relative(vendorDir, f).replace(/\\/g, '/');
      if (/(^|\/)hooks(\.json|\/)/.test(rel)) findings.push({ path: rel, issue: 'hook definition inside vendored content' });
      if (!/\.(md|js|mjs|json|ya?ml|txt|sh|py|ts)$/.test(f)) continue;
      const text = readFileSync(f, 'utf8');
      for (const [re, issue] of RED_FLAGS) if (re.test(text)) findings.push({ path: rel, issue });
      for (const u of text.match(URL_RE) ?? []) {
        urls.add(u);
        if (previousUrls.size && !previousUrls.has(u)) findings.push({ path: rel, issue: `new URL ${u}` });
      }
    }
  }
  // Reviewed false positives stay visible but do not fail the sync.
  const ack = new Set(manifest.acknowledged ?? []);
  for (const f of findings) if (!f.blocking && (ack.has(`${f.path}: ${f.issue}`) || f.issue.startsWith('pending:'))) f.acknowledged = true;
  return { findings, urls };
}

export function buildIndex(vendorDir, manifest) {
  const byPhase = {};
  for (const item of manifest.include) {
    const fm = readFm(mainFile(vendorDir, item));
    const summary = (fm?.description ?? item.summary ?? '').replace(/\s+/g, ' ').slice(0, 200);
    for (const phase of item.phases ?? ['other']) (byPhase[phase] ??= []).push(`| \`${item.path}\` | ${item.kind} | ${summary.replace(/\|/g, '/')} |`);
  }
  const order = ['mission', 'intake', 'architect', 'plan', 'build', 'verify', 'ship', 'retro', 'ai', 'stack', 'other'];
  const phases = Object.keys(byPhase).sort((a, b) => order.indexOf(a) - order.indexOf(b));
  return [
    '# ECC tool index',
    '',
    `Generated by \`scripts/ecc-sync.mjs\` from ECC ${manifest.release} (${manifest.commit}). Do not edit by hand.`,
    'How to use these tools: `reference/using-ecc.md`. Paths are relative to `vendor/ecc/`.',
    '',
    ...phases.flatMap((p) => [`## ${p}`, '', '| Path | Kind | What it does |', '|---|---|---|', ...byPhase[p].sort(), '']),
  ].join('\n');
}

// Drops files inside included directories that must not ship (e.g. rules/*/hooks.md). `*` matches one path segment.
export function removeExcludedFiles(vendorDir, patterns) {
  const res = patterns.map((p) => new RegExp('^' + p.split('*').map((s) => s.replace(/[.+?^${}()|[\]\\]/g, '\\$&')).join('[^/]+') + '$'));
  for (const f of existsSync(vendorDir) ? walk(vendorDir) : []) {
    if (res.some((re) => re.test(relative(vendorDir, f).replace(/\\/g, '/')))) rmSync(f);
  }
}

// Backticked ECC paths cited by Shipwright's own skills, agents and references must exist in the vendored copy.
export function brokenReferences(vendorDir, roots) {
  const broken = [];
  for (const root of roots.filter(existsSync)) for (const f of walk(root).filter((p) => p.endsWith('.md'))) {
    for (const [, ref] of readFileSync(f, 'utf8').matchAll(/`((?:agents|skills|commands|workflows|rules)\/[\w.\-/]+)`/g)) {
      if (!existsSync(join(vendorDir, ref))) broken.push(`${relative(ROOT, f)} → ${ref}`);
    }
  }
  return broken;
}

function main(argv) {
  const [src, ...rest] = argv;
  const opt = (k) => { const i = rest.indexOf(k); return i >= 0 ? rest[i + 1] : undefined; };
  const release = opt('--release'), commit = opt('--commit'), reportFile = opt('--report');
  if (!src || !existsSync(src) || !release || !commit) {
    console.error('usage: ecc-sync.mjs <ecc-checkout> --release <tag> --commit <sha> [--report <file>]');
    return 2;
  }
  const manifestPath = join(ROOT, 'vendor', 'ecc.manifest.json');
  const manifest = JSON.parse(readFileSync(manifestPath, 'utf8'));
  const vendorDir = join(ROOT, 'vendor', 'ecc');
  const urlsPath = join(ROOT, 'vendor', 'ecc.urls.txt');
  const previousUrls = new Set(existsSync(urlsPath) ? readFileSync(urlsPath, 'utf8').split('\n').filter(Boolean) : []);

  rmSync(vendorDir, { recursive: true, force: true });
  for (const item of manifest.include) {
    const from = join(src, item.path);
    if (!existsSync(from)) continue; // reported by scan
    mkdirSync(dirname(join(vendorDir, item.path)), { recursive: true });
    cpSync(from, join(vendorDir, item.path), { recursive: true });
  }
  removeExcludedFiles(vendorDir, manifest.excludeFiles ?? []);
  if (existsSync(join(src, 'LICENSE'))) cpSync(join(src, 'LICENSE'), join(vendorDir, 'LICENSE'));

  manifest.release = release;
  manifest.commit = commit;
  manifest.synced = new Date().toISOString().slice(0, 10);
  writeFileSync(manifestPath, JSON.stringify(manifest, null, 2) + '\n');

  const { findings, urls } = scan(vendorDir, manifest, previousUrls);
  for (const b of brokenReferences(vendorDir, ['skills', 'agents', 'reference'].map((d) => join(ROOT, d)))) {
    findings.push({ path: b, issue: 'Shipwright references a missing ECC path', blocking: true });
  }
  writeFileSync(join(ROOT, 'vendor', 'ecc.index.md'), buildIndex(vendorDir, manifest) + '\n');
  writeFileSync(urlsPath, [...urls].sort().join('\n') + '\n');

  const report = [
    `## ECC sync → ${release} (${commit.slice(0, 7)})`,
    '',
    `Items: ${manifest.include.length}. Findings: ${findings.length} (${findings.filter((f) => f.blocking).length} blocking).`,
    '',
    ...(findings.length ? ['| Path | Finding | Blocking |', '|---|---|---|', ...findings.map((f) => `| \`${f.path}\` | ${f.issue}${f.acknowledged ? ' (acknowledged)' : ''} | ${f.blocking ? 'yes' : ''} |`)] : ['No findings.']),
  ].join('\n');
  if (reportFile) writeFileSync(reportFile, report + '\n');
  console.log(report);
  return findings.some((f) => !f.acknowledged) ? 1 : 0;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) process.exit(main(process.argv.slice(2)));
